function getRelatedSongs(artist,title,Artist_Title){
	jQuery.ajax({
		method: "POST",
		url: "../php/songs.php",
		data: {
			functionname: "getRelatedSongs",
			param1: artist,
			param2: title,
			param3: Artist_Title
		},
		success: function (response) {
			result = JSON.parse(response);
			
			if (result){
								
				text = '';
				
				$.each(result, function (i) {
					if (result[i].duet){duet = duetIcon; infotext = ' Duet';}else{duet = '';}
					if (result[i].karaoke){karaoke = karaokeIcon; infotext = ' Karaoke';}else{karaoke = '';}
					if (result[i].karaoke_duet){karaoke_duet = karaokeIcon + duetIcon; infotext = 'Karaoke & Duet';}else{karaoke_duet = '';}
					if (!(result[i].duet) && !(result[i].karaoke) && !(result[i].karaoke_duet)){singalong = singalongIcon; infotext = 'Sing-a-long';}else{singalong = '';}
						
					text += '<div id="elm">';
					text += '<div id="elmType" onclick="songDetails(' + i + ')">' + singalong + karaoke_duet + duet + karaoke +'</div>';
					text += '<div id="elmTxt" onclick="songDetails(' + i + ')">' + infotext + '</div>';
					text += '</div>';
					
				});
			
				$('#songVariant').html(text);
								
			} else {
				
				txt = 'extra variant';
			}
			
			
		},
		error: function (e) {
			$("#detailsResult").html(e);
		}
	});
}

